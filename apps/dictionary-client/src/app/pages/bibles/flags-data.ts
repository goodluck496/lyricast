export function findLanguage(lang: string | null | undefined): LanguageOption | undefined {
  if (!lang) return undefined;
  const clean = lang.toLowerCase().trim();
  return LANGUAGES_OPTIONS.find(
    (l) =>
      l.code.toLowerCase() === clean ||
      l.aliases.some((a) => a.toLowerCase() === clean) ||
      l.nameRu.toLowerCase() === clean ||
      l.nameEn.toLowerCase() === clean
  );
}

export async function svgFlagToDataUrl(
  flagUrl: string,
  _width?: number,
  _height?: number
): Promise<string> {
  const base = document.baseURI?.replace(/\/+$/, '') || '';
  const cleanPath = flagUrl.replace(/^\/+/, '');
  const resolvedUrl = flagUrl.startsWith('http')
    ? flagUrl
    : base
      ? `${base}/${cleanPath}`
      : `/${cleanPath}`;

  const res = await fetch(resolvedUrl);
  if (!res.ok) {
    throw new Error(`Failed to fetch flag SVG from ${resolvedUrl}: ${res.statusText}`);
  }
  let svgText = await res.text();
  if (!/width\s*=/i.test(svgText)) {
    svgText = svgText.replace(/<svg\b/i, '<svg width="640" height="480"');
  }
  const base64 = btoa(unescape(encodeURIComponent(svgText)));
  return `data:image/svg+xml;base64,${base64}`;
}
