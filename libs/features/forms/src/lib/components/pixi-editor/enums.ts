/**
 * Общие типы-перечисления для редактора PixiJS
 * 
 * Этот файл содержит переиспользуемые типы, которые используются
 * в различных частях редактора для обеспечения типобезопасности.
 */

/**
 * Типы узлов, которые могут быть созданы в редакторе.
 * Каждый тип соответствует определенному классу узла.
 */
export type NodeType = 
  | 'text'      // Текстовый блок с автоподбором размера шрифта
  | 'image'     // Статическое изображение
  | 'video'     // Видео-элемент
  | 'iframe'    // Встроенный iframe (отображается через DOM overlay)
  | 'shape'     // Примитивная фигура (прямоугольник, эллипс, линия)
  | 'group'     // Группа узлов
  | 'brush';    // Рисунок кистью (свободная линия)

/**
 * Типы фигур для ShapeNode.
 */
export type ShapeType = 
  | 'rect'      // Прямоугольник с закругленными углами
  | 'ellipse'   // Эллипс
  | 'line';     // Прямая линия

/**
 * Горизонтальное выравнивание текста.
 */
export type TextAlign = 
  | 'left'      // Выравнивание по левому краю
  | 'center'    // Выравнивание по центру
  | 'right';    // Выравнивание по правому краю

/**
 * Соотношения сторон для границ сцены.
 */
export type AspectRatio = 
  | '16:9'      // Широкоформатное соотношение (HD)
  | '4:3'       // Классическое соотношение
  | 'none';     // Без ограничений

/**
 * Названия хэндлов для изменения размера и поворота узла.
 * 
 * Восемь хэндлов изменения размера названы по сторонам света:
 * - nw (north-west) - верхний левый угол
 * - n (north) - верхняя середина
 * - ne (north-east) - верхний правый угол
 * - e (east) - правая середина
 * - se (south-east) - нижний правый угол
 * - s (south) - нижняя середина
 * - sw (south-west) - нижний левый угол
 * - w (west) - левая середина
 * - rot (rotation) - хэндл поворота (над верхней серединой)
 */
export type HandleName = 
  | 'nw' | 'n' | 'ne' 
  | 'e' 
  | 'se' | 's' | 'sw' 
  | 'w' 
  | 'rot';

/**
 * Типы курсоров для различных операций.
 */
export type CursorType =
  | 'default'
  | 'move'
  | 'grab'
  | 'grabbing'
  | 'ns-resize'    // Изменение размера по вертикали
  | 'ew-resize'    // Изменение размера по горизонтали
  | 'nesw-resize'  // Изменение размера по диагонали (↗↙)
  | 'nwse-resize'; // Изменение размера по диагонали (↖↘)

/**
 * Режимы работы редактора.
 */
export type EditorMode =
  | 'select'    // Режим выбора и редактирования узлов
  | 'brush'     // Режим рисования кистью
  | 'text';     // Режим редактирования текста

/**
 * Направления для изменения z-index узлов.
 */
export type ZIndexDirection =
  | 'front'     // На передний план (самый верхний)
  | 'back'      // На задний план (самый нижний)
  | 'forward'   // На один слой вперед
  | 'backward'; // На один слой назад
